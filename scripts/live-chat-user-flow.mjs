import { chromium } from 'playwright-core'
const browser = await chromium.connectOverCDP('http://127.0.0.1:9234', {timeout:5000})
const page = browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('/dist/index.html'))
if (!page) throw new Error('Freya app page missing')
page.setDefaultTimeout(3000)
const text = () => page.locator('body').innerText()
console.log('START', (await text()).slice(-350))
if (!(await text()).includes('FREYA · CHAT')) {
  const open = page.locator('button[aria-label="Open Chats"]')
  if (await open.count()) await open.click()
}
console.log('CHAT_OPEN',(await text()).includes('FREYA · CHAT'))
const textarea=page.locator('textarea[placeholder="Ask Freya..."]')
console.log('COMPOSER',await textarea.count())
const search=page.getByRole('switch',{name:'Web search'})
const use=page.getByRole('switch',{name:'Browser'})
console.log('TOGGLES',await search.getAttribute('aria-checked'),await use.getAttribute('aria-checked'))
await textarea.fill('Hello Freya. This is a live UI test. Please reply with one short greeting and do not use tools.')
console.log('DRAFT',await textarea.inputValue())
await page.locator('button[aria-label="Send message"]').click()
console.log('SENT', (await text()).slice(-600))
await page.waitForTimeout(9000)
console.log('AFTER_9S', (await text()).slice(-1400))
console.log('COMPOSER_AFTER',await textarea.inputValue())
await browser.close()
